import { promises as fs } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
export interface SvgIndexPluginOptions {
    inputDir?: string            // Directory containing SVG icon files
    outputFile?: string          // Output path for generated index.ts
    prefix?: string              // Optional component-name prefix (e.g. 'Icon')
    banner?: string              // Optional banner text at file top
}
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
// Convert a string into PascalCase
function toPascal(str: string) {
    return str
        .replace(/[^a-zA-Z0-9]+/g, ' ') // Replace non-alphanumeric chars with spaces
        .split(' ')
        .filter(Boolean)
        .map(s => s.charAt(0).toUpperCase() + s.slice(1))
        .join('');
}

export const svgIndexPlugin = async (options?: SvgIndexPluginOptions) => {
    const { inputDir, outputFile, prefix, banner } = options || {};

    const ICON_DIR = inputDir||path.resolve(__dirname,'../../src/assets/icons')
    const INDEX_FILE = path.join(ICON_DIR, outputFile || 'index.ts')

    const files = (await fs.readdir(ICON_DIR)).filter(f => f.endsWith('.svg'))

    const lines = files.map(f => {
        const base = f.replace(/\.svg$/, '')
        // Convert to PascalCase: close-eyes -> CloseEyes
        const compName = `${prefix || 'Icon'}${toPascal(base)}`
        return `export { ReactComponent as ${compName} } from './${f}';`
    })

    const banner1 = banner || `/* This file is auto-generated by svg-index-plugin. Do not edit manually. */\n`

    await fs.writeFile(INDEX_FILE, banner1 + lines.join('\n') + '\n')
    console.log('✔ icons index generated:', INDEX_FILE)
}
